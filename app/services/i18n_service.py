def category_labels(lang):
    from app.models.menu import CategoryTranslation
    if lang not in ('en', 'ja'):
        return {}
    return {t.category: getattr(t, f'name_{lang}') for t in CategoryTranslation.query.all() if getattr(t, f'name_{lang}')}
