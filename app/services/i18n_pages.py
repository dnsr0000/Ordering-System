_WEEKDAYS = {'一': ('Mon', '月'), '二': ('Tue', '火'), '三': ('Wed', '水'), '四': ('Thu', '木'), '五': ('Fri', '金'),
             '六': ('Sat', '土'), '日': ('Sun', '日')}


def _weekdays(days, lang):
    """供應日：週一、三、五 → Mon, Wed, Fri / 月・水・金"""
    names = [_WEEKDAYS[d][0 if lang == 'en' else 1] for d in days.split('、') if d in _WEEKDAYS]
    return ('Available on ' + ', '.join(names)) if lang == 'en' else ('提供日：' + '・'.join(names))


def _percent_off(pay, lang):
    """85 折 / 9 折 / 0.5 折 (應付比例) → 15% off"""
    try:
        ratio = float(pay)
    except ValueError:
        return f'{pay} 折'
    if ratio < 10:   # 9 折 / 8.5 折 / 0.5 折 → 應付 90% / 85% / 5%
        ratio *= 10
    off = 100 - ratio
    off_text = f'{int(off)}' if off == int(off) else f'{off:g}'
    return f'{off_text}% off' if lang == 'en' else f'{off_text}% オフ'


